/** Language chosen in the settings. */
enum class AppLanguage { SYSTEM, DE, EN }

fun AppLanguage.resolve(): Lang = when (this) {
    AppLanguage.DE -> Lang.DE
    AppLanguage.EN -> Lang.EN
    AppLanguage.SYSTEM -> if (Locale.getDefault().language == "de") Lang.DE else Lang.EN
}

